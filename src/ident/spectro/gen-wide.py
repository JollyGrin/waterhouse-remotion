# SPECTRO 16:9: meter data for the landscape side column, measured from the exact mix.
# Reads public/ident/audio/spectro/mix.wav (written by gen-audio.py; this script never touches the audio,
# the tape or data.ts) and writes src/ident/spectro/wide-data.ts:
#   PK[f]   sample peak (dBFS) inside video frame f
#   RMS[f]  300 ms RMS (dBFS) ending at the end of frame f (meter ballistics)
#   HIST[k] 50 ms RMS (dBFS) at 4 points per frame (k = 4 f + j), for the loudness history graph
#   HIST_PRE floor used for the graph's history before frame 0
import numpy as np, wave, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
FPS, FRAMES, SUB = 30, 140, 4

with wave.open(os.path.join(ROOT, "public", "ident", "audio", "spectro", "mix.wav"), "rb") as w:
    sr = w.getframerate()
    ch = w.getnchannels()
    x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(float) / 32768
x = x.reshape(-1, ch).mean(axis=1)


def db(v):
    return float(np.round(20 * np.log10(max(v, 1e-6)), 1))


def rms(a, b):
    a, b = max(0, a), min(len(x), b)
    return np.sqrt(np.mean(x[a:b] ** 2)) if b > a else 0.0


PK, RMS, HIST = [], [], []
for f in range(FRAMES):
    a, b = int(f / FPS * sr), int((f + 1) / FPS * sr)
    PK.append(db(np.max(np.abs(x[a:b])) if b > a else 0))
    RMS.append(db(rms(b - int(0.3 * sr), b)))
    for j in range(SUB):
        e = int((f + (j + 1) / SUB) / FPS * sr)
        HIST.append(db(rms(e - int(0.05 * sr), e)))
pre = float(np.round(np.mean(HIST[: 8 * SUB]), 1))

out = f"""// GENERATED by src/ident/spectro/gen-wide.py from public/ident/audio/spectro/mix.wav — do not edit by hand.
export const MSUB = {SUB};
/** sample peak (dBFS) per video frame */
export const PK: number[] = {PK};
/** 300 ms RMS (dBFS) ending at each video frame */
export const RMS: number[] = {RMS};
/** 50 ms RMS (dBFS), {SUB} points per frame */
export const HIST: number[] = {HIST};
export const HIST_PRE = {pre};
"""
with open(os.path.join(HERE, "wide-data.ts"), "w") as fh:
    fh.write(out)
print("peak max", max(PK), "rms range", min(RMS), max(RMS), "pre", pre)
