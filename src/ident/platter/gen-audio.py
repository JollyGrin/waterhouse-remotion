# /// script
# requires-python = ">=3.10"
# dependencies = ["numpy"]
# ///
# PLATTER: the single source of truth for the record's rotation, and the sound derived from it.
#
# Writes:
#   src/ident/platter/motion.ts          rotation angle theta(u) in degrees, 8 samples per frame (generated)
#   public/ident/audio/platter/mix.wav   the whole soundtrack, sample-locked to that rotation
#
# Deck A (the record on screen) is physically modelled: the stylus reads a pressed "record" R(tau)
# at tau = theta / 200 (33 1/3 rpm = 200 deg/s), so stops, the rewind, the scratches and the
# power-off brake all come out of the same curve the picture uses. Crackle is pressed into the
# record too, so it repeats when the record is scratched and stops when the record stops.
# Deck B (the other deck) plays the beat: kicks, hats, sub.
import numpy as np, wave, os

SR = 48000
FPS = 30
FRAMES = 140
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "..", "public", "ident", "audio", "platter")
os.makedirs(OUT, exist_ok=True)
rng = np.random.default_rng(33)

# ---------------- timeline (frames; 120 bpm, beat = 15 f) ----------------
NEEDLE = 2  # needle drop
STOP = 30  # hand stops the record (on the kick)
STOP_D = 3.5
REW = 34.5  # rewind (spinback)
LOCK = 45  # caught dead, mark upright, the drop
REW_DEG = 540.0
HOLD = 75  # the DJ holds the record still: title
RELEASE = 90  # let go
REL_D = 4
BRAKE = 97  # power-off brake
BRAKE_D = 27
RINGS = 106  # rings start opening
LIFT = 127  # stylus lift
V0 = 200.0 / FPS  # deg per frame at 33 1/3

# scratch strokes: (u0, u1, from, to)
STROKES = [
    # beat 1: baby scratches on the 16ths
    (45.0, 48.75, 0, 48), (48.75, 52.5, 48, 0), (52.5, 56.25, 0, 48), (56.25, 60.0, 48, 0),
    # beat 2: a slow drag (transformed), a snap back, then chirps
    (60.0, 65.0, 0, 72), (65.0, 67.5, 72, 0),
    (67.5, 69.375, 0, 36), (69.375, 71.25, 36, 0), (71.25, 73.125, 0, 36), (73.125, 75.0, 36, 0),
]
# crossfader for deck A: closed intervals (frames)
FADER_CLOSED = []
# transformer chops on 32nds during the drag (open, closed, open, closed ...)
u = 60.0
i = 0
while u < 65.0 - 1e-6:
    if i % 2 == 1:
        FADER_CLOSED.append((u, u + 1.875))
    u += 1.875
    i += 1
FADER_CLOSED += [(69.375, 71.25), (73.125, 75.0)]  # chirps: back strokes silent

# ---------------- rotation ----------------
STEP = 1.0 / 400  # integration step in frames
uu = np.arange(0, FRAMES + 1 + STEP / 2, STEP)
v = np.zeros_like(uu)


def smooth(x):
    x = np.clip(x, 0, 1)
    return x * x * (3 - 2 * x)


# A: spinning from the start
m = uu < STOP
v[m] = V0
# B: hand stop, linear decel
m = (uu >= STOP) & (uu < STOP + STOP_D)
v[m] = V0 * (1 - (uu[m] - STOP) / STOP_D)
# D: rewind, fast ramp, sustain, hard catch on LOCK
m = (uu >= REW) & (uu < LOCK)
t = uu[m] - REW
d = LOCK - REW
shape = smooth(t / 2.2) * (1 - smooth((t - (d - 1.3)) / 1.3))
shape *= 1 + 0.25 * np.sin(np.pi * t / d)  # a hand's push, a little faster mid-spin
v[m] = -shape / (shape.sum() * STEP) * REW_DEG
# E: scratches (cosine-eased strokes; velocity zero at each turn)
for (a, b, p, q) in STROKES:
    m = (uu >= a) & (uu < b)
    v[m] = (q - p) * (np.pi / 2) / (b - a) * np.sin(np.pi * (uu[m] - a) / (b - a))
# G: release
m = (uu >= RELEASE) & (uu < RELEASE + REL_D)
v[m] = V0 * smooth((uu[m] - RELEASE) / REL_D)
m = (uu >= RELEASE + REL_D) & (uu < BRAKE)
v[m] = V0
# I: power-off brake
m = (uu >= BRAKE) & (uu < BRAKE + BRAKE_D)
v[m] = V0 * (1 - (uu[m] - BRAKE) / BRAKE_D) ** 1.6

theta_rel = np.concatenate([[0], np.cumsum(v[:-1]) * STEP])
# choose theta0 so the mark is exactly upright (0 deg) at LOCK
iL = int(round(LOCK / STEP))
theta0 = -theta_rel[iL]
theta = theta0 + theta_rel
print("theta0 = %.2f, theta(LOCK) = %.4f, theta(end) = %.2f" % (theta0, theta[iL], theta[-1]))

# export 8 samples per frame
SUB = 8
idx = (np.arange(0, FRAMES * SUB + 1) / SUB / STEP).round().astype(int)
samples = theta[idx]
with open(os.path.join(HERE, "motion.ts"), "w") as fh:
    fh.write("// GENERATED by src/ident/platter/gen-audio.py: do not edit. Record angle in degrees, 8 samples per frame.\n")
    fh.write("export const THETA_SUB = %d;\n" % SUB)
    fh.write("export const THETA: number[] = [%s];\n" % ",".join("%.3f" % x for x in samples))

# ---------------- audio helpers ----------------
DUR = 5.2
N = int(DUR * SR)
ts = np.arange(N) / SR
fu = ts * FPS  # frame time of each sample


def onepole_lp(x, fc):
    fc = np.broadcast_to(np.asarray(fc, dtype=float), x.shape)
    a = 1 - np.exp(-2 * np.pi * np.minimum(fc, SR * 0.45) / SR)
    y = np.empty_like(x)
    s = 0.0
    for i in range(len(x)):
        s += a[i] * (x[i] - s)
        y[i] = s
    return y


def hp(x, fc):
    return x - onepole_lp(x, fc)


def place(buf, x, frame, gain=1.0):
    i0 = int(round(frame / FPS * SR))
    n = min(len(x), len(buf) - i0)
    if n > 0:
        buf[i0:i0 + n] += x[:n] * gain


def kick(dur, f0, f1, sweep, decay, drive, click=0.3):
    t = np.arange(int(dur * SR)) / SR
    f = f1 + (f0 - f1) * np.exp(-t / sweep)
    ph = 2 * np.pi * np.cumsum(f) / SR
    body = np.sin(ph) * np.exp(-t / decay)
    body = np.tanh(body * drive) / np.tanh(drive)
    c = hp(rng.standard_normal(len(t)) * np.exp(-t / 0.004), 2500) * click
    return (body + c) * np.minimum(1, t / 0.0015)


# ---------------- the pressed record R(tau) ----------------
RDUR = 3.4
RN = int(RDUR * SR)
rt = np.arange(RN) / SR
rec = np.zeros(RN)


def saw(f, t):
    return 2 * ((f * t) % 1) - 1


def formant_ahh(dur, f0=132.0):
    t = np.arange(int(dur * SR)) / SR
    vib = 1 + 0.012 * np.sin(2 * np.pi * 5.5 * t)
    ph = np.cumsum(f0 * vib * (1 - 0.06 * t / dur)) / SR
    src = 2 * (ph % 1) - 1 + 0.15 * rng.standard_normal(len(t))
    out = np.zeros_like(t)
    for fc, bw, g in [(730, 90, 1.0), (1090, 110, 0.55), (2440, 170, 0.28), (3400, 250, 0.12)]:
        # 2-pole resonator
        r = np.exp(-np.pi * bw / SR)
        th = 2 * np.pi * fc / SR
        a1, a2 = -2 * r * np.cos(th), r * r
        y = np.zeros_like(src)
        y1 = y2 = 0.0
        for i in range(len(src)):
            y0 = src[i] - a1 * y1 - a2 * y2
            y[i] = y0
            y2, y1 = y1, y0
        out += g * y / np.max(np.abs(y))
    env = np.minimum(1, t / 0.006) * np.exp(-np.maximum(0, t - 0.16) / 0.07)
    return np.tanh(out * env * 1.6)


def chord(dur, root, decay, cutoff):
    t = np.arange(int(dur * SR)) / SR
    x = np.zeros_like(t)
    for semi in (0, 3, 7, 10, 14):  # minor 9 voicing: dub chord
        f = root * 2 ** (semi / 12)
        for det in (-0.004, 0.004):
            x += saw(f * (1 + det), t + rng.random())
    env = np.minimum(1, t / 0.004) * np.exp(-t / decay)
    fc = 180 + cutoff * np.exp(-t / (decay * 0.5))
    return onepole_lp(onepole_lp(x * env, fc), fc * 1.3) * 0.25


# the scratch sample at tau 0: "ahh"
ahh = formant_ahh(0.30)
rec[: len(ahh)] += ahh * 0.95
# the track after it: a long dub chord (what the power-off drags down)
ch = chord(1.1, 98.0, 0.55, 2400)
i0 = int(0.26 * SR)
rec[i0:i0 + len(ch)] += ch[: RN - i0] * 1.3
# the intro the record is playing when we arrive: dub chords on the offbeats, a pad, ticks
for tau in (1.392, 1.892, 2.392, 2.892):
    c = chord(0.5, 98.0, 0.16, 2600)
    j = int(tau * SR)
    rec[j:j + len(c)] += c[: RN - j] * 1.1
pad_t = rt[int(0.4 * SR):]
pad = sum(np.sin(2 * np.pi * f * pad_t + p) for f, p in [(49.0, 0), (98.0, 1), (146.8, 2), (196.0, 0.5)])
pad = onepole_lp(pad * 0.12 + rng.standard_normal(len(pad_t)) * 0.03, 900)
rec[int(0.4 * SR):] += pad
for tau in np.arange(0.4, RDUR, 0.125):  # ticks (16ths): texture for the rewind
    n = int(0.03 * SR)
    tk = hp(rng.standard_normal(n), 6000) * np.exp(-np.arange(n) / SR / 0.008) * 0.18
    j = int(tau * SR)
    rec[j:j + n] += tk[: RN - j]
# vinyl: surface noise and pops, pressed into the record
surface = hp(onepole_lp(rng.standard_normal(RN), 5000), 900) * 0.025
rec += surface
npops = int(RDUR * 34)
for _ in range(npops):
    j = int(rng.random() * (RN - 200))
    amp = (rng.random() ** 3) * 0.55 + 0.04
    w = int(2 + rng.random() * 18)
    pop = rng.standard_normal(w) * np.hanning(w) * amp
    rec[j:j + w] += pop

# ---------------- deck A: stylus follows theta ----------------
th_a = np.interp(fu, uu, theta)  # degrees, per audio sample
vel = np.interp(fu, uu, v)  # deg / frame
tau = th_a / 200.0
tau_c = np.clip(tau, 0, RDUR - 0.001)
deckA = np.interp(tau_c * SR, np.arange(RN), rec)
speed = np.abs(vel) / V0
# cartridge: output falls with speed, top end closes as the record slows
gain = np.where(speed < 1, np.power(np.maximum(speed, 0), 0.75), 1 + 0.18 * np.log(np.maximum(speed, 1)))
fc = 250 + 15000 * np.minimum(1, speed) ** 1.4
fc = np.where(speed > 1, 15000 / np.sqrt(np.maximum(speed, 1)), fc)
deckA = onepole_lp(deckA * gain, fc)
deckA = hp(deckA, 25)
# needle on/off, crossfader
on = np.clip((fu - NEEDLE) * 4, 0, 1) * np.clip((LIFT - fu) * 4, 0, 1)
fader = np.ones(N)
for (a, b) in FADER_CLOSED:
    fader[(fu >= a) & (fu < b)] = 0
fader = onepole_lp(fader, 400)  # 2-3 ms edges, no clicks
deckA *= on * fader

# needle drop and lift
nd = np.zeros(int(0.25 * SR))
tn = np.arange(len(nd)) / SR
nd += np.sin(2 * np.pi * 62 * tn) * np.exp(-tn / 0.03) * 0.6
nd += hp(rng.standard_normal(len(nd)), 1500) * np.exp(-tn / 0.012) * 0.5
lift = hp(rng.standard_normal(int(0.04 * SR)), 2000) * np.exp(-np.arange(int(0.04 * SR)) / SR / 0.005) * 0.35

# ---------------- deck B: the beat ----------------
deckB = np.zeros(N)
k_small = kick(0.5, 150, 46, 0.03, 0.15, 2.4)
k_big = kick(1.3, 135, 41, 0.045, 0.38, 3.2, click=0.4)
tk = np.arange(len(k_big)) / SR
k_big = k_big + onepole_lp(rng.standard_normal(len(k_big)), 700) * np.exp(-tk / 0.3) * 0.25
for f in (15, 30, 60, 90):
    place(deckB, k_small, f, 0.85)
for f in (45, 75):
    place(deckB, k_big, f, 1.0)
for f in (22.5, 52.5, 67.5, 82.5):
    n = int(0.06 * SR)
    hat = hp(rng.standard_normal(n), 7000) * np.exp(-np.arange(n) / SR / 0.018) * 0.22
    place(deckB, hat, f)
# sub under the scratching, ducked by the kicks, cut on the release
sub = np.sin(2 * np.pi * 41.2 * ts) + 0.25 * np.sin(2 * np.pi * 82.4 * ts)
duck = np.ones(N)
for f in (45, 60, 75, 90):
    tt = (fu - f) / FPS
    m = tt >= 0
    duck[m] *= 1 - 0.85 * np.exp(-tt[m] / 0.09)
subenv = np.clip((fu - LOCK) * 2, 0, 1) * np.clip((RELEASE + 1 - fu) * 1.5, 0, 1)
deckB += sub * subenv * duck * 0.14

# room: low drone / booth air, the whole way, dying with the power
room = onepole_lp(rng.standard_normal(N), 300) * 0.6 + 0.25 * np.sin(2 * np.pi * 55 * ts)
roomenv = np.clip(fu / 8, 0, 1) * np.clip((132 - fu) / 20, 0, 1)
bed = room * roomenv * 0.08

# the rings open: a soft low thump and air
thump = kick(1.2, 80, 34, 0.06, 0.4, 1.6, click=0.05)
air_n = int(0.8 * SR)
ta = np.arange(air_n) / SR
air = onepole_lp(rng.standard_normal(air_n), 300 + 2500 * (ta / 0.8)) * np.sin(np.pi * ta / 0.8) ** 2 * 0.25

mix = deckA * 0.9 + deckB + bed
place(mix, nd, NEEDLE, 0.8)
place(mix, lift, LIFT, 0.7)
place(mix, thump, RINGS, 0.55)
place(mix, air, RINGS - 4, 0.6)
fade = np.clip((DUR - ts) / 0.15, 0, 1)
mix = mix * fade
mix = np.tanh(mix / np.max(np.abs(mix)) * 1.4) / np.tanh(1.4)  # gentle limiting only on the peaks


def save(name, x, peak_db=-1.5):
    x = x / (np.max(np.abs(x)) + 1e-9) * (10 ** (peak_db / 20))
    with wave.open(os.path.join(OUT, name), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((x * 32767).astype(np.int16).tobytes())


save("mix.wav", mix)
if os.environ.get("STEMS"):
    spf = SR // FPS
    for nm, x in (("A", deckA), ("B", deckB)):
        print(nm, " ".join("%d" % max(0, 60 + 20 * np.log10(np.sqrt(np.mean(x[k * spf:(k + 1) * spf] ** 2)) + 1e-9)) for k in range(30, 128)))
rms = 20 * np.log10(np.sqrt(np.mean((mix / np.max(np.abs(mix))) ** 2)) + 1e-9)
print("ok, rms %.1f dB rel peak" % rms)
