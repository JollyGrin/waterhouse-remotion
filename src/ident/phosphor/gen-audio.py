# /// script
# requires-python = ">=3.10"
# dependencies = ["numpy"]
# ///
# PHOSPHOR: Scope's first half → Platter's second half, as one signal.
#
# Writes:
#   src/ident/phosphor/motion.ts          record angle theta(u) in degrees, 8 samples per frame (generated)
#   public/ident/audio/phosphor/mix.wav   48 kHz stereo, sample-locked to src/ident/Phosphor.tsx
#
#   f0–60   SCOPE: power-on dot, flat line + mains hum, kick waveforms (15, 30), the 3:2 Lissajous,
#           the beam pulls the mark out of it and locks on the big kick (60). L = beam x, R = beam y.
#   f60–75  THE MATERIALISE: the beam traces the label and the grooves (each circle is a pure tone in
#           quadrature, so you hear the rings being drawn), the needle drops (64) and the record spins up
#           two turns (65–75). The XY figure rotates with the record and its buzz bends up with the
#           speed while deck A zips through the pressing; the beam fades out under the print.
#   f75–    PLATTER: caught dead on the drop (75), baby scratches + chirps, held for the title (90),
#           release (105), power-off brake (109), the grooves part into rings (116).
#
# Deck A is the record on screen, physically modelled exactly like src/ident/platter/gen-audio.py: the stylus
# reads a pressing R(tau) at tau = theta / 200 + T0, so the spin-up, scratches and brake come from the
# same curve the picture uses.
import numpy as np, wave, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scratchkit"))
import kit  # real-vocal scratch kit: Denzo "Waterhouse", friction, fader clicks

SR = 48000
FPS = 30
FRAMES = 150
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "..", "public", "ident", "audio", "phosphor")
os.makedirs(OUT, exist_ok=True)
rng = np.random.default_rng(57)

# ---------------- timeline (frames; 120 bpm, beat = 15 f) ----------------
LOCK = 60  # scope: the mark locks (big kick)
CIRCLES = [(61, 65), (62, 66.5), (63, 68), (64, 69.5), (65, 71)]  # beam traces label + grooves
NEEDLE = 64
SPIN0, SPIN1 = 65, 75  # two turns forward, caught dead upright on the drop
SPIN_DEG = 720.0
DROP = 75
HOLD = 90  # title
RELEASE = 105
REL_D = 4
BRAKE = 109
BRAKE_D = 24
RINGS = 116
LIFT = 137
V0 = 200.0 / FPS  # deg per frame at 33 1/3

STROKES = [
    (75.0, 78.75, 0, 48), (78.75, 82.5, 48, 0),  # baby scratches on the 16ths
    (82.5, 84.375, 0, 36), (84.375, 86.25, 36, 0), (86.25, 88.125, 0, 36), (88.125, 90.0, 36, 0),  # chirps
]
FADER_CLOSED = [(84.375, 86.25), (88.125, 90.0)]  # chirps: back strokes silent
STROKES = kit.scale_strokes(STROKES)

# ---------------- rotation ----------------
STEP = 1.0 / 400
uu = np.arange(0, FRAMES + 1 + STEP / 2, STEP)
v = np.zeros_like(uu)


def smooth01(x):
    x = np.clip(x, 0, 1)
    return x * x * (3 - 2 * x)


m = (uu >= SPIN0) & (uu < SPIN1)
t = uu[m] - SPIN0
d = SPIN1 - SPIN0
shape = smooth01(t / 3.0) * (1 - smooth01((t - (d - 1.3)) / 1.3))
shape *= 1 + 0.2 * np.sin(np.pi * t / d)
v[m] = shape / (shape.sum() * STEP) * SPIN_DEG
for (a, b, p, q) in STROKES:
    m = (uu >= a) & (uu < b)
    v[m] = (q - p) * (np.pi / 2) / (b - a) * np.sin(np.pi * (uu[m] - a) / (b - a))
m = (uu >= RELEASE) & (uu < RELEASE + REL_D)
v[m] = V0 * smooth01((uu[m] - RELEASE) / REL_D)
m = (uu >= RELEASE + REL_D) & (uu < BRAKE)
v[m] = V0
m = (uu >= BRAKE) & (uu < BRAKE + BRAKE_D)
v[m] = V0 * (1 - (uu[m] - BRAKE) / BRAKE_D) ** 1.6

theta_rel = np.concatenate([[0], np.cumsum(v[:-1]) * STEP])
iD = int(round(DROP / STEP))
theta = theta_rel - theta_rel[iD]  # upright (0) at the drop; -720 before the spin
print("theta(0) = %.2f, theta(DROP) = %.4f, theta(end) = %.2f, peak %.1f deg/f" % (theta[0], theta[iD], theta[-1], v.max()))

SUB = 8
idx = (np.arange(0, FRAMES * SUB + 1) / SUB / STEP).round().astype(int)
with open(os.path.join(HERE, "motion.ts"), "w") as fh:
    fh.write("// GENERATED by src/ident/phosphor/gen-audio.py: do not edit. Record angle in degrees, 8 samples per frame.\n")
    fh.write("export const THETA_SUB = %d;\n" % SUB)
    fh.write("export const THETA: number[] = [%s];\n" % ",".join("%.3f" % x for x in theta[idx]))

# ---------------- helpers ----------------
DUR = FRAMES / FPS + 0.3
N = int(DUR * SR)
ts = np.arange(N) / SR
fu = ts * FPS


def lp(x, fc, order=2):
    X = np.fft.rfft(x)
    fq = np.fft.rfftfreq(len(x), 1 / SR)
    X *= 1 / np.sqrt(1 + (fq / fc) ** (2 * order))
    return np.fft.irfft(X, len(x))


def hp(x, fc, order=2):
    X = np.fft.rfft(x)
    fq = np.fft.rfftfreq(len(x), 1 / SR)
    X *= 1 / np.sqrt(1 + (fc / np.maximum(fq, 1e-3)) ** (2 * order))
    return np.fft.irfft(X, len(x))


def onepole_lp(x, fc):
    fc = np.broadcast_to(np.asarray(fc, dtype=float), x.shape)
    a = 1 - np.exp(-2 * np.pi * np.minimum(fc, SR * 0.45) / SR)
    y = np.empty_like(x)
    s = 0.0
    for i in range(len(x)):
        s += a[i] * (x[i] - s)
        y[i] = s
    return y


def sm(a, b, x):
    s = np.clip((x - a) / (b - a), 0, 1)
    return s * s * (3 - 2 * s)


def place(buf, x, frame, gain=1.0):
    i0 = int(round(frame / FPS * SR))
    n = min(len(x), len(buf) - i0)
    if n > 0:
        buf[i0:i0 + n] += x[:n] * gain


def kick(dur, f0, f1, sweep, decay, drive, click=0.3):
    tt = np.arange(int(dur * SR)) / SR
    f = f1 + (f0 - f1) * np.exp(-tt / sweep)
    ph = 2 * np.pi * np.cumsum(f) / SR
    body = np.tanh(np.sin(ph) * np.exp(-tt / decay) * drive) / np.tanh(drive)
    c = hp(rng.standard_normal(len(tt)) * np.exp(-tt / 0.003), 2500) * click
    return (body + c) * np.minimum(1, tt / 0.0015)


L = np.zeros(N)
R = np.zeros(N)


def both(x, f, g=1.0):
    place(L, x, f, g)
    place(R, x, f, g)


# ================= SCOPE (f0–75) =================
k_scope = kick(0.6, 165, 48, 0.035, 0.17, 2.0)
for f in (15, 30, 45):
    both(k_scope, f, 0.8)
kb = kick(1.5, 150, 42, 0.05, 0.45, 3.0, click=0.4)
tb = np.arange(len(kb)) / SR
kb = kb + lp(rng.standard_normal(len(kb)), 700) * np.exp(-tb / 0.3) * 0.5
both(kb, LOCK, 0.95)

# mains hum: power-on until the glass fades away
hum = sum(a * np.sin(2 * np.pi * 50 * h * ts) for h, a in [(1, 1), (2, 0.5), (3, 0.35), (5, 0.12), (7, 0.06)])
hum = np.tanh(hum * 1.5) * 0.06 * sm(2, 6, fu) * (1 - sm(64, 74, fu))
L += hum
R += hum

# power-on: relay tick + degauss thoom
tt = np.arange(int(0.9 * SR)) / SR
thoom = np.sin(2 * np.pi * np.cumsum(38 + 40 * np.exp(-tt / 0.08)) / SR) * np.exp(-tt / 0.25)
thoom += lp(rng.standard_normal(len(tt)), 400) * np.exp(-tt / 0.12) * 0.8
tick = hp(rng.standard_normal(len(tt)), 3000) * np.exp(-tt / 0.002) * 0.6
both(thoom * 0.5 + tick, 2, 0.6)

# the XY signal: the mark (normalised, y up), the 3:2 Lissajous, the kick waveform rides the hum
POLY = [
    [(348, 3), (0, 283), (0, 665), (348, 665)],
    [(379.6, 48.7), (685.2, 149), (685.2, 287.5), (379.6, 204.4)],
    [(722.2, 161), (1000, 252.3), (1000, 372.9), (722.2, 297.6)],
    [(596.6, 398), (775.1, 438.8), (775.1, 665.9), (596.6, 665.9)],
]
pts = []
for poly in POLY:
    loop = poly + [poly[0]]
    for a, b in zip(loop[:-1], loop[1:]):
        mm = max(2, int(np.hypot(b[0] - a[0], b[1] - a[1]) / 4))
        for j in range(mm):
            pts.append((a[0] + (b[0] - a[0]) * j / mm, a[1] + (b[1] - a[1]) * j / mm))
P = (np.array(pts) - [500, 333]) / 500.0
P[:, 1] *= -1


def trace(phase):
    u = (phase % 1) * len(P)
    i = np.floor(u).astype(int)
    fr_ = u - i
    a = P[i % len(P)]
    b = P[(i + 1) % len(P)]
    return a + (b - a) * fr_[:, None]


# rotation of the record, per sample (screen clockwise = negative in y-up audio coords)
th_s = np.interp(fu, uu, theta)
vel = np.interp(fu, uu, v)
speed = np.abs(vel) / V0
spin_on = (fu >= SPIN0) & (fu < DROP + 2)
peak = np.max(speed[spin_on]) if spin_on.any() else 1
base = 55.0
bend = 1 + 0.9 * np.where(spin_on, speed / peak, 0)  # the buzz bends up with the spin
freq = base * bend
phase = np.cumsum(freq) / SR
logo = trace(phase)
ang = -np.radians(np.where(fu < SPIN0, 0, th_s - theta[0]))
cx, sx = np.cos(ang), np.sin(ang)
lx = logo[:, 0] * cx - logo[:, 1] * sx
ly = logo[:, 0] * sx + logo[:, 1] * cx

phi = (fu - 33) * 0.16
lisx = np.sin(2 * np.pi * 3 * base * ts + phi) * 0.8
lisy = np.sin(2 * np.pi * 2 * base * ts) * 0.6
fold = sm(33, 47, fu)
morph = sm(45, 60, fu)
smear = 4 * morph * (1 - morph)
x = (1 - morph) * lisx + morph * lx + smear * 0.12 * np.sin(2 * np.pi * 23 * base * ts)
y = (1 - morph) * lisy + morph * ly + smear * 0.12 * np.cos(2 * np.pi * 17 * base * ts)

# the circles the beam traces: label 440, grooves 520 / 742 / 990 / 1262 → pure tones in quadrature
for k, ((a, b), r, fq) in enumerate(zip(CIRCLES, [440, 520, 742, 990, 1262], [220.0, 196.0, 146.8, 110.0, 82.4])):
    g = sm(a - 0.5, a + 0.5, fu) * (1 - sm(b + 1, b + 6, fu)) * 0.32 * (r / 1262) ** 0.3
    x = x + g * np.cos(2 * np.pi * fq * ts + k)
    y = y + g * np.sin(2 * np.pi * fq * ts + k)

gate = fold * (1 - sm(68, 78, fu))  # the beam fades under the print; deck A takes over
lvl = 0.16 * gate * (1 + 0.6 * np.exp(-np.maximum(fu - LOCK, 0) / 5) * (fu >= LOCK))
L += lp(x * lvl, 2600)
R += lp(y * lvl, 2600)

# scope room floor
room0 = lp(rng.standard_normal(N), 300) * 0.05 * sm(0, 10, fu) * (1 - sm(66, 76, fu))
L += room0
R += room0

# ================= PLATTER (deck A + deck B, f64–) =================
T0 = 4.0  # tau offset so the spin-up (theta -720 → 0) reads real grooves
RDUR = T0 + 1.6
RN = int(RDUR * SR)
rt = np.arange(RN) / SR
rec = np.zeros(RN)


def saw(f, t):
    return 2 * ((f * t) % 1) - 1


def formant_ahh(dur, f0=132.0):
    t = np.arange(int(dur * SR)) / SR
    vib = 1 + 0.012 * np.sin(2 * np.pi * 5.5 * t)
    ph = np.cumsum(f0 * vib * (1 - 0.06 * t / dur)) / SR
    src = 2 * (ph % 1) - 1 + 0.15 * rng.standard_normal(len(t))
    out = np.zeros_like(t)
    for fc, bw, g in [(730, 90, 1.0), (1090, 110, 0.55), (2440, 170, 0.28), (3400, 250, 0.12)]:
        r = np.exp(-np.pi * bw / SR)
        th = 2 * np.pi * fc / SR
        a1, a2 = -2 * r * np.cos(th), r * r
        yy = np.zeros_like(src)
        y1 = y2 = 0.0
        for i in range(len(src)):
            y0 = src[i] - a1 * y1 - a2 * y2
            yy[i] = y0
            y2, y1 = y1, y0
        out += g * yy / np.max(np.abs(yy))
    env = np.minimum(1, t / 0.006) * np.exp(-np.maximum(0, t - 0.16) / 0.07)
    return np.tanh(out * env * 1.6)


def chord(dur, root, decay, cutoff):
    t = np.arange(int(dur * SR)) / SR
    xx = np.zeros_like(t)
    for semi in (0, 3, 7, 10, 14):
        f = root * 2 ** (semi / 12)
        for det in (-0.004, 0.004):
            xx += saw(f * (1 + det), t + rng.random())
    env = np.minimum(1, t / 0.004) * np.exp(-t / decay)
    fc = 180 + cutoff * np.exp(-t / (decay * 0.5))
    return onepole_lp(onepole_lp(xx * env, fc), fc * 1.3) * 0.25


# the scratch sample at tau T0, then the long chord the brake drags down
voc = kit.vocal()
j0 = int(T0 * SR)
rec[j0:j0 + len(voc)] += voc * 1.0
ch = chord(1.1, 98.0, 0.55, 2400)
i0 = int((T0 + 0.58) * SR)
rec[i0:i0 + len(ch)] += ch[: RN - i0] * 1.3
# what the spin-up zips through: dub chords, a pad and ticks before T0
for tau in np.arange(0.3, T0 - 0.2, 0.5):
    c = chord(0.5, 98.0, 0.16, 2600)
    j = int(tau * SR)
    rec[j:j + len(c)] += c[: RN - j] * 1.1
pad = sum(np.sin(2 * np.pi * f * rt + p) for f, p in [(49.0, 0), (98.0, 1), (146.8, 2), (196.0, 0.5)])
pad = lp(pad * 0.12 + rng.standard_normal(RN) * 0.03, 900) * (rt < T0 - 0.05)
rec += pad
for tau in np.arange(0.3, T0, 0.125):
    n = int(0.03 * SR)
    tk = hp(rng.standard_normal(n), 6000) * np.exp(-np.arange(n) / SR / 0.008) * 0.18
    j = int(tau * SR)
    rec[j:j + n] += tk[: RN - j]
rec += hp(lp(rng.standard_normal(RN), 5000), 900) * 0.025  # surface noise
for _ in range(int(RDUR * 34)):  # pops, pressed in
    j = int(rng.random() * (RN - 200))
    amp = (rng.random() ** 3) * 0.55 + 0.04
    w = int(2 + rng.random() * 18)
    rec[j:j + w] += rng.standard_normal(w) * np.hanning(w) * amp

# deck A: the stylus follows theta
tau = np.clip(th_s / 200.0 + T0, 0, RDUR - 0.001)
deckA = np.interp(tau * SR, np.arange(RN), rec)
gain = np.where(speed < 1, np.power(np.maximum(speed, 0), 0.75), 1 + 0.18 * np.log(np.maximum(speed, 1)))
fc = 250 + 15000 * np.minimum(1, speed) ** 1.4
fc = np.where(speed > 1, 15000 / np.sqrt(np.maximum(speed, 1)), fc)
deckA = onepole_lp(deckA * gain, fc)
deckA = hp(deckA, 25)
on = np.clip((fu - NEEDLE) * 4, 0, 1) * np.clip((LIFT - fu) * 4, 0, 1)
fader = np.ones(N)
for (a, b) in FADER_CLOSED:
    fader[(fu >= a) & (fu < b)] = 0
fader = onepole_lp(fader, 400)
deckA += kit.friction(fu, speed, STROKES, rng)  # the rub is heard through the stylus
deckA *= on * fader * (0.55 + 0.45 * sm(70, 76, fu))  # the zip sits under the bending buzz, then takes over
deckA += kit.fader_clicks(fu, FADER_CLOSED) * on

nd = np.zeros(int(0.25 * SR))
tn = np.arange(len(nd)) / SR
nd += np.sin(2 * np.pi * 62 * tn) * np.exp(-tn / 0.03) * 0.6
nd += hp(rng.standard_normal(len(nd)), 1500) * np.exp(-tn / 0.012) * 0.5
lift = hp(rng.standard_normal(int(0.04 * SR)), 2000) * np.exp(-np.arange(int(0.04 * SR)) / SR / 0.005) * 0.35

# deck B: the beat
deckB = np.zeros(N)
k_small = kick(0.5, 150, 46, 0.03, 0.15, 2.4)
k_big = kick(1.3, 135, 41, 0.045, 0.38, 3.2, click=0.4)
tk = np.arange(len(k_big)) / SR
k_big = k_big + lp(rng.standard_normal(len(k_big)), 700) * np.exp(-tk / 0.3) * 0.25
place(deckB, k_small, RELEASE, 0.85)
for f in (DROP, HOLD):
    place(deckB, k_big, f, 1.0)
for f in (97.5,):  # no hats under the scratch
    n = int(0.06 * SR)
    hat = hp(rng.standard_normal(n), 7000) * np.exp(-np.arange(n) / SR / 0.018) * 0.22
    place(deckB, hat, f)
sub = np.sin(2 * np.pi * 41.2 * ts) + 0.25 * np.sin(2 * np.pi * 82.4 * ts)
duck = np.ones(N)
for f in (DROP, HOLD, RELEASE):
    tt = (fu - f) / FPS
    mm = tt >= 0
    duck[mm] *= 1 - 0.85 * np.exp(-tt[mm] / 0.09)
subenv = np.clip((fu - DROP) * 2, 0, 1) * np.clip((RELEASE + 1 - fu) * 1.5, 0, 1)
subenv = subenv * (1 - kit.scratch_gate(fu, STROKES, sm))
deckB += sub * subenv * duck * 0.14

room = lp(rng.standard_normal(N), 300) * 0.6 + 0.25 * np.sin(2 * np.pi * 55 * ts)
room = room * sm(64, 76, fu) * np.clip((142 - fu) / 20, 0, 1) * 0.08

thump = kick(1.2, 80, 34, 0.06, 0.4, 1.6, click=0.05)
air_n = int(0.8 * SR)
ta = np.arange(air_n) / SR
air = lp(rng.standard_normal(air_n), 1500) * np.sin(np.pi * ta / 0.8) ** 2 * 0.25

mono = deckA * 0.9 + deckB + room
place(mono, nd, NEEDLE, 0.8)
place(mono, lift, LIFT, 0.7)
place(mono, thump, RINGS, 0.55)
place(mono, air, RINGS - 4, 0.6)
L += mono
R += mono

S = np.stack([L, R], 1)
S *= np.clip((DUR - ts) / 0.15, 0, 1)[:, None]
S = np.tanh(S / np.max(np.abs(S)) * 1.4) / np.tanh(1.4)
S = S / np.max(np.abs(S)) * 10 ** (-1.5 / 20)
with wave.open(os.path.join(OUT, "mix.wav"), "wb") as wv:
    wv.setnchannels(2)
    wv.setsampwidth(2)
    wv.setframerate(SR)
    wv.writeframes((S * 32767).astype(np.int16).tobytes())
spf = SR // FPS
env = [20 * np.log10(np.sqrt(np.mean(S[k * spf:(k + 1) * spf] ** 2)) + 1e-9) for k in range(FRAMES)]
print("mix.wav", S.shape, "rms dB %.1f" % (20 * np.log10(np.sqrt(np.mean(S ** 2)))))
print("per-5f rms:", " ".join("%d" % round(np.mean(env[k:k + 5])) for k in range(0, FRAMES, 5)))
