# /// script
# requires-python = ">=3.10"
# dependencies = ["numpy"]
# ///
# GROOVE: Scope's opening, the Lissajous resolves to a spinning circle that becomes the record,
# then Platter's second half. Single source of truth for the record's rotation and the soundtrack.
#
# Writes:
#   src/ident/groove/motion.ts          record angle theta(u) in degrees, 8 samples per frame (generated)
#   public/ident/audio/groove/mix.wav   stereo soundtrack (48 kHz s16), sample-locked to that rotation
#
# The bridge is one signal:
#   - the Lissajous's y channel is a 110 Hz sine (Scope's 3:2 figure on a 55 Hz base);
#   - the 1:1 circle is the record's tone in quadrature: x = cos(ph), y = sin(ph), ph = 2*pi*110*(tau - c),
#     tau = theta / 200 (33 1/3 rpm = 200 deg/s). While the record runs at speed tau advances 1 s/s,
#     and c is chosen so that y is the Lissajous's y exactly: no seam when x glides from 165 Hz to the circle;
#   - the same tone is pressed into the record, so when the stylus (deck A, mono) takes over from the
#     XY bed it reads the very sine the circle was, slowed by the hand stop and wound back by the spinback,
#     landing on the drop.
# Then Platter's second half: scratches, title hold, release, power-off brake, rings.
import numpy as np, wave, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scratchkit"))
import kit  # real-vocal scratch kit: Denzo "Waterhouse", friction, fader clicks

SR = 48000
FPS = 30
FRAMES = 150
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "..", "public", "ident", "audio", "groove")
os.makedirs(OUT, exist_ok=True)
rng = np.random.default_rng(57)

# ---------------- timeline (frames; 120 bpm, beat = 15 f) ----------------
ON = 2
KICKS_SCOPE = [15, 30, 45]
FOLD = (33, 47)
GLIDE = (46, 51)  # Lissajous -> 1:1 circle
EXPAND = (50.5, 53)  # the circle swells to the record's rim
SPIRAL = (53, 59)  # the beam spirals in to the label edge
STOP = 52.5  # hand stops the record
STOP_D = 2.5
REW = 55.5  # spinback
LOCK = 60  # caught dead, mark upright: the drop
REW_DEG = 360.0
HOLD = 90  # title
RELEASE = 105
REL_D = 3
BRAKE = 109
BRAKE_D = 24
RINGS = 115
LIFT = 134
V0 = 200.0 / FPS  # deg per frame at 33 1/3

# Platter's scratch strokes, shifted to the new drop (+15)
SH = LOCK - 45
STROKES = [(a + SH, b + SH, p, q) for (a, b, p, q) in [
    (45.0, 48.75, 0, 48), (48.75, 52.5, 48, 0), (52.5, 56.25, 0, 48), (56.25, 60.0, 48, 0),
    (60.0, 65.0, 0, 72), (65.0, 67.5, 72, 0),
    (67.5, 69.375, 0, 36), (69.375, 71.25, 36, 0), (71.25, 73.125, 0, 36), (73.125, 75.0, 36, 0),
]]
FADER_CLOSED = []
u = 60.0 + SH
i = 0
while u < 65.0 + SH - 1e-6:
    if i % 2 == 1:
        FADER_CLOSED.append((u, u + 1.875))
    u += 1.875
    i += 1
FADER_CLOSED += [(69.375 + SH, 71.25 + SH), (73.125 + SH, 75.0 + SH)]
STROKES = kit.scale_strokes(STROKES)

# ---------------- rotation ----------------
STEP = 1.0 / 400
uu = np.arange(0, FRAMES + 1 + STEP / 2, STEP)
v = np.zeros_like(uu)


def smooth(x):
    x = np.clip(x, 0, 1)
    return x * x * (3 - 2 * x)


m = uu < STOP
v[m] = V0
m = (uu >= STOP) & (uu < STOP + STOP_D)
v[m] = V0 * (1 - (uu[m] - STOP) / STOP_D)
m = (uu >= REW) & (uu < LOCK)
t = uu[m] - REW
d = LOCK - REW
shape = smooth(t / 1.2) * (1 - smooth((t - (d - 0.9)) / 0.9))
shape *= 1 + 0.25 * np.sin(np.pi * t / d)
v[m] = -shape / (shape.sum() * STEP) * REW_DEG
for (a, b, p, q) in STROKES:
    m = (uu >= a) & (uu < b)
    v[m] = (q - p) * (np.pi / 2) / (b - a) * np.sin(np.pi * (uu[m] - a) / (b - a))
m = (uu >= RELEASE) & (uu < RELEASE + REL_D)
v[m] = V0 * smooth((uu[m] - RELEASE) / REL_D)
m = (uu >= RELEASE + REL_D) & (uu < BRAKE)
v[m] = V0
m = (uu >= BRAKE) & (uu < BRAKE + BRAKE_D)
v[m] = V0 * (1 - (uu[m] - BRAKE) / BRAKE_D) ** 1.6

theta_rel = np.concatenate([[0], np.cumsum(v[:-1]) * STEP])
iL = int(round(LOCK / STEP))
theta = theta_rel - theta_rel[iL]  # mark exactly upright at the drop
print("theta(0) = %.2f, theta(LOCK) = %.4f, theta(end) = %.2f" % (theta[0], theta[iL], theta[-1]))

SUB = 8
idx = (np.arange(0, FRAMES * SUB + 1) / SUB / STEP).round().astype(int)
with open(os.path.join(HERE, "motion.ts"), "w") as fh:
    fh.write("// GENERATED by src/ident/groove/gen-audio.py: do not edit. Record angle in degrees, 8 samples per frame.\n")
    fh.write("export const THETA_SUB = %d;\n" % SUB)
    fh.write("export const THETA: number[] = [%s];\n" % ",".join("%.3f" % x for x in theta[idx]))

# ---------------- audio helpers ----------------
DUR = FRAMES / FPS + 0.3
N = int(DUR * SR)
ts = np.arange(N) / SR
fu = ts * FPS


def onepole_lp(x, fc):
    fc = np.broadcast_to(np.asarray(fc, dtype=float), x.shape)
    a = 1 - np.exp(-2 * np.pi * np.minimum(fc, SR * 0.45) / SR)
    y = np.empty_like(x)
    s = 0.0
    for i in range(len(x)):
        s += a[i] * (x[i] - s)
        y[i] = s
    return y


def hp(x, fc):
    return x - onepole_lp(x, fc)


def lp_fft(x, fc, order=2):
    X = np.fft.rfft(x)
    fq = np.fft.rfftfreq(len(x), 1 / SR)
    X *= 1 / np.sqrt(1 + (fq / fc) ** (2 * order))
    return np.fft.irfft(X, len(x))


def hp_fft(x, fc, order=2):
    X = np.fft.rfft(x)
    fq = np.fft.rfftfreq(len(x), 1 / SR)
    X *= 1 / np.sqrt(1 + (fc / np.maximum(fq, 1e-3)) ** (2 * order))
    return np.fft.irfft(X, len(x))


def sm(a, b, x):
    s = np.clip((x - a) / (b - a), 0, 1)
    return s * s * (3 - 2 * s)


def place(buf, x, frame, gain=1.0):
    i0 = int(round(frame / FPS * SR))
    n = min(len(x), len(buf) - i0)
    if n > 0:
        buf[i0:i0 + n] += x[:n] * gain


def kick(dur, f0, f1, sweep, decay, drive, click=0.3):
    t = np.arange(int(dur * SR)) / SR
    f = f1 + (f0 - f1) * np.exp(-t / sweep)
    ph = 2 * np.pi * np.cumsum(f) / SR
    body = np.sin(ph) * np.exp(-t / decay)
    body = np.tanh(body * drive) / np.tanh(drive)
    c = hp_fft(rng.standard_normal(len(t)) * np.exp(-t / 0.004), 2500) * click
    return (body + c) * np.minimum(1, t / 0.0015)


th_a = np.interp(fu, uu, theta)
vel = np.interp(fu, uu, v)
tau = th_a / 200.0
# c: while the record runs at speed, tau = t + c
i50 = int(50 / FPS * SR)
C_OFF = tau[i50] - ts[i50]
print("tau(f33..f52) = %.3f .. %.3f, c = %.4f" % (tau[int(33 / FPS * SR)], tau[int(52 / FPS * SR)], C_OFF))

L = np.zeros(N)
R = np.zeros(N)


def both(x, frame, g=1.0):
    place(L, x, frame, g)
    place(R, x, frame, g)


# ================= first half: Scope =================
# power-on: relay tick + degauss thoom
dd = 0.9
tt = np.arange(int(dd * SR)) / SR
thoom = np.sin(2 * np.pi * np.cumsum(38 + 40 * np.exp(-tt / 0.08)) / SR) * np.exp(-tt / 0.25)
thoom += lp_fft(rng.standard_normal(len(tt)), 400) * np.exp(-tt / 0.12) * 0.8
tick = hp_fft(rng.standard_normal(len(tt)), 3000) * np.exp(-tt / 0.002) * 0.6
both(thoom * 0.5 + tick, ON, 0.6)

# kicks (Scope's)
k_scope = kick(0.6, 165, 48, 0.035, 0.17, 2.0)
for fk in KICKS_SCOPE:
    both(k_scope, fk, 0.8)

# mains hum: power-on until the glass gives way to the vinyl
hum = sum(a * np.sin(2 * np.pi * 50 * h * ts) for h, a in [(1, 1), (2, 0.5), (3, 0.35), (5, 0.12), (7, 0.06)])
hum = np.tanh(hum * 1.5) * 0.06 * sm(2, 6, fu) * (1 - sm(53, 59, fu))
L += hum
R += hum

# the XY bed
base = 55.0
phi = (fu - 33) * 0.16
lisx = np.sin(2 * np.pi * 3 * base * ts + phi)
lisy = np.sin(2 * np.pi * 2 * base * ts)
ph = 2 * np.pi * 110.0 * (tau - C_OFF)
cirx = np.cos(ph)
ciry = np.sin(ph)
k = sm(*GLIDE, fu)
x = (1 - k) * lisx + k * cirx
y = (1 - k) * lisy + k * ciry
# radius: 1 for the Lissajous and the settled circle; the swell to the rim, then the spiral tightening
# to the label edge (screen ratios ~ 4.3 at the rim, 1.47 at the label), compressed
e = sm(*EXPAND, fu)
p = np.clip((fu - SPIRAL[0]) / (SPIRAL[1] - SPIRAL[0]), 0, 1)
eo = 1 - (1 - p) ** 2
r_rel = np.where(fu < SPIRAL[0], 1 + e * 2.0, 3.0 + (1.47 - 3.0) * eo)
amp = np.sqrt(r_rel)
fold = sm(*FOLD, fu)
gate = fold * (1 - sm(56, 60, fu))
lvl = 0.16 * gate * amp * (1 + 0.6 * np.exp(-np.maximum(fu - 45, 0) / 4) * (fu >= 45) * (1 - k))
L += lp_fft(x * lvl, 2600)
R += lp_fft(y * lvl, 2600)

# Scope's room floor
room_s = lp_fft(rng.standard_normal(N), 300) * 0.05 * sm(0, 10, fu) * (1 - sm(54, 60, fu))
L += room_s
R += room_s

# ================= the pressed record R(tau) =================
RDUR = 2.1
RN = int(RDUR * SR)
rt = np.arange(RN) / SR
rec = np.zeros(RN)


def saw(f, t):
    return 2 * ((f * t) % 1) - 1


def formant_ahh(dur, f0=132.0):
    t = np.arange(int(dur * SR)) / SR
    vib = 1 + 0.012 * np.sin(2 * np.pi * 5.5 * t)
    phs = np.cumsum(f0 * vib * (1 - 0.06 * t / dur)) / SR
    src = 2 * (phs % 1) - 1 + 0.15 * rng.standard_normal(len(t))
    out = np.zeros_like(t)
    for fc, bw, g in [(730, 90, 1.0), (1090, 110, 0.55), (2440, 170, 0.28), (3400, 250, 0.12)]:
        r = np.exp(-np.pi * bw / SR)
        th = 2 * np.pi * fc / SR
        a1, a2 = -2 * r * np.cos(th), r * r
        yy = np.zeros_like(src)
        y1 = y2 = 0.0
        for i in range(len(src)):
            y0 = src[i] - a1 * y1 - a2 * y2
            yy[i] = y0
            y2, y1 = y1, y0
        out += g * yy / np.max(np.abs(yy))
    env = np.minimum(1, t / 0.006) * np.exp(-np.maximum(0, t - 0.16) / 0.07)
    return np.tanh(out * env * 1.6)


def chord(dur, root, decay, cutoff):
    t = np.arange(int(dur * SR)) / SR
    xx = np.zeros_like(t)
    for semi in (0, 3, 7, 10, 14):
        f = root * 2 ** (semi / 12)
        for det in (-0.004, 0.004):
            xx += saw(f * (1 + det), t + rng.random())
    env = np.minimum(1, t / 0.004) * np.exp(-t / decay)
    fc = 180 + cutoff * np.exp(-t / (decay * 0.5))
    return onepole_lp(onepole_lp(xx * env, fc), fc * 1.3) * 0.25


voc = kit.vocal()
rec[: len(voc)] += voc * 1.0
ch = chord(0.75, 98.0, 0.45, 2400)
i0 = int(0.58 * SR)
rec[i0:i0 + len(ch)] += ch[: RN - i0] * 1.3
# the circle's tone, pressed where the record sat while the beam drew it (tau ~1.1..1.8)
tone_m = (rt >= 0.95) & (rt < 1.95)
tone_env = sm(0.95, 1.02, rt) * (1 - sm(1.88, 1.95, rt))
rec += np.sin(2 * np.pi * 110.0 * (rt - C_OFF)) * tone_env * 0.55 * tone_m
for tq in np.arange(0.4, RDUR, 0.125):  # ticks: texture for the spinback
    n = int(0.03 * SR)
    tk = hp_fft(rng.standard_normal(n), 6000) * np.exp(-np.arange(n) / SR / 0.008) * 0.16
    j = int(tq * SR)
    rec[j:j + n] += tk[: RN - j]
rec += hp(onepole_lp(rng.standard_normal(RN), 5000), 900) * 0.025
for _ in range(int(RDUR * 34)):
    j = int(rng.random() * (RN - 200))
    a = (rng.random() ** 3) * 0.55 + 0.04
    w = int(2 + rng.random() * 18)
    rec[j:j + w] += rng.standard_normal(w) * np.hanning(w) * a

# ================= second half: Platter =================
tau_c = np.clip(tau, 0, RDUR - 0.001)
deckA = np.interp(tau_c * SR, np.arange(RN), rec)
speed = np.abs(vel) / V0
gain = np.where(speed < 1, np.power(np.maximum(speed, 0), 0.75), 1 + 0.18 * np.log(np.maximum(speed, 1)))
fc = 250 + 15000 * np.minimum(1, speed) ** 1.4
fc = np.where(speed > 1, 15000 / np.sqrt(np.maximum(speed, 1)), fc)
deckA = onepole_lp(deckA * gain, fc)
deckA = hp(deckA, 25)
on = sm(54, 57.5, fu) * np.clip((LIFT - fu) * 4, 0, 1)
fader = np.ones(N)
for (a, b) in FADER_CLOSED:
    fader[(fu >= a) & (fu < b)] = 0
fader = onepole_lp(fader, 400)
deckA = (deckA + kit.friction(fu, speed, STROKES, rng)) * on * fader  # the rub is heard through the stylus
deckA += kit.fader_clicks(fu, FADER_CLOSED) * on

# the stylus meets the vinyl as the glass gives way
nd = np.zeros(int(0.25 * SR))
tn = np.arange(len(nd)) / SR
nd += np.sin(2 * np.pi * 62 * tn) * np.exp(-tn / 0.03) * 0.6
nd += hp_fft(rng.standard_normal(len(nd)), 1500) * np.exp(-tn / 0.012) * 0.5
lift = hp_fft(rng.standard_normal(int(0.04 * SR)), 2000) * np.exp(-np.arange(int(0.04 * SR)) / SR / 0.005) * 0.35

deckB = np.zeros(N)
k_small = kick(0.5, 150, 46, 0.03, 0.15, 2.4)
k_big = kick(1.3, 135, 41, 0.045, 0.38, 3.2, click=0.4)
tkb = np.arange(len(k_big)) / SR
k_big = k_big + onepole_lp(rng.standard_normal(len(k_big)), 700) * np.exp(-tkb / 0.3) * 0.25
for fk in (105,):  # no kick under the scratch
    place(deckB, k_small, fk, 0.85)
for fk in (LOCK, HOLD):
    place(deckB, k_big, fk, 1.0)
for fh in (97.5,):
    n = int(0.06 * SR)
    hat = hp_fft(rng.standard_normal(n), 7000) * np.exp(-np.arange(n) / SR / 0.018) * 0.22
    place(deckB, hat, fh)
sub = np.sin(2 * np.pi * 41.2 * ts) + 0.25 * np.sin(2 * np.pi * 82.4 * ts)
duck = np.ones(N)
for fk in (LOCK, HOLD, 105):
    tt2 = (fu - fk) / FPS
    mm = tt2 >= 0
    duck[mm] *= 1 - 0.85 * np.exp(-tt2[mm] / 0.09)
subenv = np.clip((fu - LOCK) * 2, 0, 1) * np.clip((RELEASE + 1 - fu) * 1.5, 0, 1)
subenv = subenv * (1 - kit.scratch_gate(fu, STROKES, sm))
deckB += sub * subenv * duck * 0.14

room = onepole_lp(rng.standard_normal(N), 300) * 0.6 + 0.25 * np.sin(2 * np.pi * 55 * ts)
roomenv = sm(52, 60, fu) * np.clip((142 - fu) / 20, 0, 1)
bed = room * roomenv * 0.08

thump = kick(1.2, 80, 34, 0.06, 0.4, 1.6, click=0.05)
air_n = int(0.8 * SR)
ta = np.arange(air_n) / SR
air = onepole_lp(rng.standard_normal(air_n), 300 + 2500 * (ta / 0.8)) * np.sin(np.pi * ta / 0.8) ** 2 * 0.25

mono = deckA * 0.9 + deckB + bed
place(mono, nd, 54, 0.45)
place(mono, lift, LIFT, 0.7)
place(mono, thump, RINGS, 0.55)
place(mono, air, RINGS - 4, 0.6)

# level-match the two halves: Scope's bed was normalised on its own; bring it up to sit with Platter's deck
S = np.stack([L * 2.2 + mono, R * 2.2 + mono], 1)
fade = np.clip((DUR - ts) / 0.15, 0, 1)[:, None]
S = S * fade
S = np.tanh(S / np.max(np.abs(S)) * 1.4) / np.tanh(1.4)
S = S / np.max(np.abs(S)) * 10 ** (-1.5 / 20)
with wave.open(os.path.join(OUT, "mix.wav"), "wb") as wv:
    wv.setnchannels(2)
    wv.setsampwidth(2)
    wv.setframerate(SR)
    wv.writeframes((S * 32767).astype(np.int16).tobytes())
spf = SR // FPS
lv = [20 * np.log10(np.sqrt(np.mean(S[kk * spf:(kk + 1) * spf] ** 2)) + 1e-9) for kk in range(FRAMES)]
print("rms dB overall %.1f" % (20 * np.log10(np.sqrt(np.mean(S ** 2)))))
print("per 5 frames:", " ".join("%d" % round(np.mean(lv[kk:kk + 5])) for kk in range(0, FRAMES, 5)))
