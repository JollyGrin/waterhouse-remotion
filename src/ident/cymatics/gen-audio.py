# /// script
# requires-python = ">=3.10"
# dependencies = ["numpy"]
# ///
# CYMATICS: sound bed + shared timeline.
#   -> public/ident/audio/cymatics/bed.wav   (48 kHz stereo s16)
#   -> src/ident/cymatics/timeline.ts        (patterns, tone frequencies, the per-frame drive amplitude, kicks)
# The tone that drives the plate IS the picture: each Chladni pattern is the plate's mode at that tone,
# the drive amplitude per frame is both the tone's level and how hard the grains jitter on screen.
import numpy as np, wave, os, json

SR = 48000
FPS = 30
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "..", "public", "ident", "audio", "cymatics")
os.makedirs(OUT, exist_ok=True)
rng = np.random.default_rng(23)

# ---------------- timeline (single source of truth) ----------------
FRAMES = 138
CLEAR = 128
LIGHT = [0, 9]  # the work light comes up on the plate
PATTERNS = [
    # (n, m, sign): f = cos(nπx)cos(mπy) + sign·cos(mπx)cos(nπy) on the unit plate
    dict(key="A", n=1, m=3, s=1, hz=110.00, start=8, dur=16, w=10.0),
    dict(key="B", n=3, m=5, s=1, hz=164.81, start=30, dur=12, w=6.0),
    dict(key="C", n=3, m=7, s=1, hz=220.00, start=45, dur=10, w=4.6),
    dict(key="D", n=5, m=9, s=1, hz=329.63, start=53, dur=8, w=3.6),
]
LOGO = dict(start=60, dur=15)  # the impossible frequency: the sand migrates into the mark
LOCK = 75  # the mark sets; title cuts in
LEAP = 90  # kick: the grains leap and land sharper
HIT = 108  # massive sub: the sand is thrown at the lens
KICKS = [15, 30, 45, 60, 75, 90]
BIG = [60, 75]

fr = np.arange(FRAMES + 20)


def env_decay(f, at, tau):
    return np.where(f >= at, np.exp(-(f - at) / tau), 0.0)


amp = np.zeros(len(fr), dtype=float)
# A fades in, every later step hits hard and decays to a sustain
amp = np.where((fr >= 8) & (fr < 30), np.minimum(1, (fr - 7) / 3) * (0.38 + 0.62 * np.exp(-np.maximum(fr - 10, 0) / 6)), amp)
for p in PATTERNS[1:]:
    end = {30: 45, 45: 53, 53: 60}[p["start"]]
    seg = (fr >= p["start"]) & (fr < end)
    amp = np.where(seg, 0.4 + 0.6 * np.exp(-(fr - p["start"]) / 5), amp)
seg = (fr >= 60) & (fr < 75)
amp = np.where(seg, 1.0 - 0.25 * (fr - 60) / 15, amp)  # searching, held hard
seg = (fr >= 75) & (fr < HIT)
amp = np.where(seg, 0.22 + 0.5 * np.exp(-(fr - 75) / 4) + 0.55 * env_decay(fr, LEAP, 4), amp)
amp = np.where(fr >= HIT, 0, amp)
AMP = [round(float(a), 4) for a in amp[:FRAMES]]

ts = f"""// GENERATED by src/ident/cymatics/gen-audio.py, do not edit. Re-run the script after timing changes.
export const CY_FRAMES = {FRAMES};
export const CY_CLEAR = {CLEAR};
export const CY_LIGHT: [number, number] = {json.dumps(LIGHT)};
export type Pattern = {{ key: string; n: number; m: number; s: number; hz: number; start: number; dur: number; w: number }};
export const CY_PATTERNS: Pattern[] = {json.dumps(PATTERNS)};
export const CY_LOGO = {json.dumps(LOGO)};
export const CY_LOCK = {LOCK};
export const CY_LEAP = {LEAP};
export const CY_HIT = {HIT};
export const CY_KICKS = {json.dumps(KICKS)};
export const CY_BIG = {json.dumps(BIG)};
/** drive amplitude per frame: the tone's level, and how hard the sand jitters */
export const CY_AMP: number[] = {json.dumps(AMP)};
"""
open(os.path.join(HERE, "timeline.ts"), "w").write(ts)

# ---------------- audio ----------------
DUR = FRAMES / FPS + 0.5
n = int(DUR * SR)
t = np.arange(n) / SR
ft = t * FPS  # frame clock


def at(f):
    return int(round(f / FPS * SR))


def lp(x, fc, order=2):
    X = np.fft.rfft(x)
    q = np.fft.rfftfreq(len(x), 1 / SR)
    X *= 1 / np.sqrt(1 + (q / fc) ** (2 * order))
    return np.fft.irfft(X, len(x))


def hp(x, fc, order=2):
    X = np.fft.rfft(x)
    q = np.fft.rfftfreq(len(x), 1 / SR)
    X *= 1 / np.sqrt(1 + (fc / np.maximum(q, 1e-3)) ** (2 * order))
    return np.fft.irfft(X, len(x))


def bp(x, lo, hi):
    return hp(lp(x, hi, 3), lo, 3)


def smooth(a, b, x):
    s = np.clip((x - a) / (b - a), 0, 1)
    return s * s * (3 - 2 * s)


L = np.zeros(n)
R = np.zeros(n)


def place(buf, x, f, g=1.0):
    i = at(f)
    m = min(len(x), len(buf) - i)
    if m > 0:
        buf[i:i + m] += x[:m] * g


def both(x, f, g=1.0, pan=0.0):
    place(L, x, f, g * (1 - max(0, pan)))
    place(R, x, f, g * (1 + min(0, pan)))


# drive amplitude at audio rate (linear between frames, but steps land on the frame exactly)
amp_t = np.interp(ft, np.arange(len(amp)), amp)

# ---- the drive tone: frequency steps on the pattern frames ----
hz = np.zeros(n)
for p, nxt in zip(PATTERNS, [30, 45, 53, 60]):
    hz = np.where((ft >= p["start"]) & (ft < nxt), p["hz"], hz)
# the impossible frequency: an inharmonic search that climbs, then locks to a clean A on the lock frame
srch = (ft >= 60) & (ft < 75)
glide = 277.18 * (1 + 0.06 * smooth(60, 75, ft))
hz = np.where(srch, glide, hz)
hz = np.where((ft >= 75) & (ft < HIT), 220.0, hz)
hz = np.where(hz == 0, 110.0, hz)
# 3 ms portamento so each step is a click-free jump that still lands on the frame
k = int(0.003 * SR)
hz_s = np.convolve(np.pad(hz, (k, 0), mode="edge"), np.ones(k) / k, mode="valid")[: n]
ph = 2 * np.pi * np.cumsum(hz_s) / SR
tone = np.sin(ph) + 0.35 * np.sin(2 * ph) + 0.18 * np.sin(3 * ph + 0.4) + 0.07 * np.sin(5 * ph)
# the search adds two beating partials, the lock adds a pure octave
beat = srch * (0.35 * np.sin(2 * np.pi * np.cumsum(hz_s * 1.498) / SR) + 0.25 * np.sin(2 * np.pi * np.cumsum(hz_s * 2.13) / SR))
lockp = ((ft >= 75) & (ft < HIT)) * 0.3 * np.sin(2 * ph)
tone = np.tanh((tone + beat + lockp) * 1.3) * 0.8
# cut dead at the hit
tone *= amp_t * (ft < HIT)
L += tone * 0.09
R += tone * 0.09

# ---- the sand itself: a patter whose density follows how much sand is moving ----
mob = np.zeros(n)
for p in PATTERNS:
    s = np.clip((ft - p["start"]) / (p["dur"]), 0, 1)
    mob = np.maximum(mob, ((ft >= p["start"]) & (s < 1)) * (1 - s) ** 1.5)
s = np.clip((ft - 60) / 15, 0, 1)
mob = np.maximum(mob, ((ft >= 60) & (s < 1)) * (0.6 + 0.4 * (1 - s)))
mob = np.maximum(mob, env_decay(ft, LEAP + 4, 3) * (ft >= LEAP + 3))
rattle_env = amp_t * (0.15 + 0.85 * mob)
# impacts at the tone rate: grains hit the plate once per cycle -> a buzzy hiss
cyc = 0.5 + 0.5 * np.sign(np.sin(ph)) * np.abs(np.sin(ph)) ** 0.3
grit = rng.standard_normal(n) * (rng.random(n) < 0.18)
rattleL = bp(grit * cyc, 1800, 9000) * rattle_env
grit2 = rng.standard_normal(n) * (rng.random(n) < 0.18)
rattleR = bp(grit2 * cyc, 1800, 9000) * rattle_env
L += rattleL * 0.26
R += rattleR * 0.26

# ---- landing patter after the leap: thousands of grains hitting the plate ----
def patter(f0, f1, count, gain, lo=2500, hi=11000, seed=0):
    r = np.random.default_rng(seed)
    out = np.zeros(n)
    times = f0 + (f1 - f0) * r.beta(1.6, 3.0, count)
    for tm in times:
        i = at(tm)
        d = int(0.0025 * SR)
        if i + d >= n:
            continue
        out[i:i + d] += r.standard_normal(d) * np.exp(-np.arange(d) / (0.0004 * SR)) * r.uniform(0.2, 1)
    return bp(out, lo, hi) * gain


p1 = patter(LEAP + 3, LEAP + 12, 1600, 0.15, seed=1)
L += p1
R += np.roll(p1, 37)

# ---- room tone ----
room = lp(rng.standard_normal(n), 300) * 0.035 * smooth(0, 8, ft) * (1 - smooth(HIT + 10, HIT + 22, ft))
L += room
R += lp(rng.standard_normal(n), 300) * 0.035 * smooth(0, 8, ft) * (1 - smooth(HIT + 10, HIT + 22, ft))


# ---- light up: a switch, a soft thud of the plate settling ----
def click(gain=0.5, dur=0.03):
    tt = np.arange(int(dur * SR)) / SR
    return hp(rng.standard_normal(len(tt)), 2500) * np.exp(-tt / 0.0025) * gain


both(click(0.45), 0)
d = 0.5
tt = np.arange(int(d * SR)) / SR
thud = np.sin(2 * np.pi * np.cumsum(55 + 30 * np.exp(-tt / 0.04)) / SR) * np.exp(-tt / 0.12)
both(thud, 1, 0.35)


# ---- kicks ----
def kick(dur, f0, f1, sweep, decay, drive, clk=0.3):
    tt = np.arange(int(dur * SR)) / SR
    f = f1 + (f0 - f1) * np.exp(-tt / sweep)
    phk = 2 * np.pi * np.cumsum(f) / SR
    body = np.tanh(np.sin(phk) * np.exp(-tt / decay) * drive) / np.tanh(drive)
    c = hp(rng.standard_normal(len(tt)) * np.exp(-tt / 0.003), 2500) * clk
    return (body + c) * np.minimum(1, tt / 0.0015)


kk = kick(0.55, 160, 47, 0.033, 0.16, 2.0)
for f in KICKS:
    if f not in BIG:
        both(kk, f, 0.75)
kb = kick(1.2, 150, 42, 0.05, 0.3, 2.6, clk=0.4)
tb = np.arange(len(kb)) / SR
kb = kb + lp(rng.standard_normal(len(kb)), 600) * np.exp(-tb / 0.25) * 0.4
for f in BIG:
    both(kb, f, 0.8)
# 16th tick on the fast step to D
both(kick(0.25, 200, 70, 0.02, 0.06, 1.5, clk=0.5), 53, 0.45)

# ---- THE HIT: a sub drop, air, and the sand falling everywhere ----
d = 2.0
tt = np.arange(int(d * SR)) / SR
fsub = 30 + 70 * np.exp(-tt / 0.07)
sub = np.tanh(np.sin(2 * np.pi * np.cumsum(fsub) / SR) * np.exp(-tt / 0.75) * 3.2) / np.tanh(3.2)
sub += hp(rng.standard_normal(len(tt)) * np.exp(-tt / 0.004), 2000) * 0.6
air = bp(rng.standard_normal(len(tt)), 400, 6000) * (np.minimum(1, tt / 0.01) * np.exp(-tt / 0.22)) * 0.7
both(sub, HIT, 1.0)
place(L, air, HIT, 0.5)
place(R, np.roll(air, 211), HIT, 0.5)
p2 = patter(HIT + 4, CLEAR, 2600, 0.16, lo=2000, hi=10000, seed=2)
L += p2
R += np.roll(p2, 61)

# ---- master ----
mix = np.stack([L, R], 1)
mix = hp(mix[:, 0], 25)[:, None] * [1, 0] + hp(mix[:, 1], 25)[:, None] * [0, 1]
fade = 1 - smooth(DUR - 0.35, DUR, t)
mix *= fade[:, None]
mix = np.tanh(mix * 0.9)
peak = np.max(np.abs(mix))
mix *= 10 ** (-1.5 / 20) / peak
rms = 20 * np.log10(np.sqrt(np.mean(mix[: at(HIT + 20)] ** 2)))
with wave.open(os.path.join(OUT, "bed.wav"), "wb") as w:
    w.setnchannels(2)
    w.setsampwidth(2)
    w.setframerate(SR)
    w.writeframes((mix * 32767).astype("<i2").tobytes())
print(f"bed.wav {DUR:.2f}s peak -1.5 dB, rms {rms:.1f} dB")
